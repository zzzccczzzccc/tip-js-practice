// Прогноз порядка меток A–F записывается ДО запуска, затем сравнивается с фактическим выводом.

console.log("A — синхронный вывод в начале файла");

setTimeout(() => {
  console.log("D — обработчик таймера с нулевой задержкой");
}, 0);

Promise.resolve().then(() => {
  console.log("C — первая микрозадача продолжения Promise");
});

console.log("B — синхронный вывод после регистрации операций");

// Асинхронная функция выполняется синхронно до первого await.
async function withAwait() {
  console.log("E — синхронная часть async-функции до await");

  await null;

  console.log("F — продолжение после await, тоже микрозадача");
}

withAwait();

// Собственный дополнительный обработчик: он поставлен в очередь микрозадач последним
